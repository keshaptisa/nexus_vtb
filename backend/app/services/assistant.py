def _state_summary(account: Account) -> str:
    live = live_risk(account)
    p = live.profile
    lines = [
        f"Клиент: {account.persona.name}, {account.persona.age} лет, баланс {account.balance:.0f} ₽.",
        f"Обычное пополнение ~{p.avg_topup:.0f} ₽ от: {', '.join(p.known_senders) or 'нет данных'}.",
        f"Обычная трата ~{p.avg_spend:.0f} ₽.",
        f"Риск сейчас: {live.level} ({live.score}).",
    ]
    if live.signals:
        lines.append("Сигналы: " + "; ".join(live.signals))
    return "\n".join(lines)


def _rules_reply(account: Account, message: str) -> AssistantResponse:
    text = message.lower()

    if any(k in text for k in ("сейчас видит", "мой риск", "что видит банк сейчас", "что сейчас")):
        live = live_risk(account)
        if live.signals:
            reply = "Сейчас банк замечает:\n— " + "\n— ".join(live.signals)
        else:
            reply = "Сейчас всё спокойно: операции совпадают с вашим обычным поведением."
        return AssistantResponse(reply=reply, suggestions=DEFAULT_SUGGESTIONS)

    for keys, reply, suggestions, action in RULES:
        if any(k in text for k in keys):
            if "{legal}" in reply:
                legal = content.legal()
                parts = [legal[k]["short"] for k in ("age_under16", "uk187", "uk187_note4", "cbr_base") if k in legal]
                reply = reply.format(legal="\n".join(f"— {x}" for x in parts))
            return AssistantResponse(reply=reply, suggestions=suggestions, action=action)

    return AssistantResponse(
        reply="Я помогаю разобраться с деньгами и безопасностью: подозрительные переводы, «подработки», "
        "мошеннические сообщения, бюджет. Выберите тему или опишите ситуацию своими словами.",
        suggestions=DEFAULT_SUGGESTIONS,
    )


SYSTEM = (
    "Ты — дружелюбный ассистент молодёжного раздела банка для клиентов 14–22 лет. Обращайся на «вы», "
    "пиши коротко и просто, без эмодзи, без осуждения. Помогаешь с безопасностью денег (дропы, "
    "мошенничество) и финграмотностью. Не выдумывай законы — опирайся только на факты из контекста. "
    "Если человек попал в схему — успокой и направь в «Безопасный выход». "
    'Ответ — строго JSON: {"reply": "...", "suggestions": ["...", "..."]}'
)


def reply(account: Account, message: str, history: list[dict]) -> AssistantResponse:
    base = _rules_reply(account, message)
    context = _state_summary(account) + "\n\nПодсказка из базы знаний:\n" + base.reply
    dialog = "\n".join(f"{m.get('role')}: {m.get('text')}" for m in history[-6:])
    data = llm.complete_json(SYSTEM, f"{context}\n\nДиалог:\n{dialog}\n\nСообщение: {message}")
    if data and isinstance(data.get("reply"), str):
        suggestions = data.get("suggestions") if isinstance(data.get("suggestions"), list) else base.suggestions
        return AssistantResponse(
            reply=data["reply"], suggestions=[str(s) for s in suggestions][:4], action=base.action, source="llm"
        )
    return base

