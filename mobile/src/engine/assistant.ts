export function reply(acc: Account, message: string): AssistantReply {
  const text = message.toLowerCase()

  if (['сейчас видит', 'мой риск', 'что видит банк сейчас', 'что сейчас'].some((k) => text.includes(k))) {
    const live = liveRisk(acc)
    return {
      reply: live.signals.length
        ? 'Сейчас банк замечает:\n— ' + live.signals.join('\n— ')
        : 'Сейчас всё спокойно: операции совпадают с вашим обычным поведением.',
      suggestions: DEFAULT_SUGGESTIONS,
      action: null,
    }
  }

  for (const [keys, answer, suggestions, action] of RULES) {
    if (!keys.some((k) => text.includes(k))) continue
    let out = answer
    if (out.includes('{legal}')) {
      const parts = ['age_under16', 'uk187', 'uk187_note4', 'cbr_base'].filter((k) => LEGAL[k]).map((k) => `— ${LEGAL[k].short}`)
      out = out.replace('{legal}', parts.join('\n'))
    }
    return { reply: out, suggestions, action }
  }

  return {
    reply:
      'Я помогаю разобраться с деньгами и безопасностью: подозрительные переводы, «подработки», мошеннические сообщения, бюджет. Выберите тему или опишите ситуацию своими словами.',
    suggestions: DEFAULT_SUGGESTIONS,
    action: null,
  }
}
